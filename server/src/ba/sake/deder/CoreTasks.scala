  val testClassesTask = CachedTaskBuilder
    .make[Seq[DiscoveredFrameworkTests]](
      name = "testClasses",
      supportedModuleTypes = Set(
        ModuleType.JAVA_TEST,
        ModuleType.SCALA_TEST,
        ModuleType.SCALA_JS_TEST,
        ModuleType.SCALA_NATIVE_TEST
      ),
      category = "Verification"
    )
    .dependsOn(compileTask)
    .dependsOn(runClasspathTask)
    .build { ctx =>
      val (_, runClasspath) = ctx.depResults
      val classesDir = DederPath(DederGlobals.classesDir(ctx.module.id))
      val runtimeClasspath = (Seq(classesDir.absPath) ++ runClasspath).reverse.distinct.reverse
      ClassLoaderUtils.withTestsClassLoader(runtimeClasspath) { classLoader =>
        val frameworkClassNames = ctx.module match {
          case m: JavaTestModule        => m.testFrameworks.asScala.toSeq
          case m: ScalaTestModule       => m.testFrameworks.asScala.toSeq
          case m: ScalaJsTestModule     => m.testFrameworks.asScala.toSeq
          case m: ScalaNativeTestModule => m.testFrameworks.asScala.toSeq
          case _                        => Seq.empty
        }
        val testDiscovery = DederTestDiscovery(
          classLoader = classLoader,
          testClassesDir = classesDir.absPath,
          testClasspath = runtimeClasspath,
          frameworkClassNames = frameworkClassNames,
          logger = DederTestLogger(ctx.notifications, ctx.module.id)
        )
        testDiscovery.discover()
      }
    }

  val testTask = TaskBuilder
    .make[DederTestResults](
      name = "test",
      supportedModuleTypes = Set(ModuleType.JAVA_TEST, ModuleType.SCALA_TEST),
      category = "Verification"
    )
    .dependsOn(runClasspathTask)
    .dependsOn(jvmOptionsTask)
    .dependsOn(javaHomeTask)
    .dependsOn(testClassesTask)
    .buildSummarized[TestResultsSummary](
      execute = { ctx =>
        val (runClasspath, jvmOptions, javaHome, discoveredTests) = ctx.depResults
        OutputCaptureContext.withCapture(ctx.notifications, ctx.module.id) {
          val cpus = Runtime.getRuntime.availableProcessors()
          def resolve(n: Int): Int = if n == 0 then cpus else n
          val (forkEnv, testParallelism, maxTestForks) = ctx.module match {
            case m: JavaTestModule =>
              (m.forkEnv.asScala.to(Map), resolve(m.testParallelism.toInt), resolve(m.maxTestForks.toInt))
            case m: ScalaTestModule =>
              (m.forkEnv.asScala.to(Map), resolve(m.testParallelism.toInt), resolve(m.maxTestForks.toInt))
            case _ => (Map.empty, cpus, cpus)
          }
          val testOptions = DederTestOptions(ctx.args)
          val clientEnv = RequestContext.current.get().envVars
          val mergedEnv = clientEnv ++ forkEnv // forkEnv wins on conflict
          val flushInterval = DederGlobals.forkTestFlushIntervalMs
          val forkedRun = ForkedTestOrchestrator.run(
            discoveredTests = discoveredTests,
            runtimeClasspath = runClasspath,
            jvmOptions = jvmOptions,
            envVars = mergedEnv,
            javaHome = javaHome.map(_.toString),
            testOptions = testOptions,
            notifications = ctx.notifications,
            moduleId = ctx.module.id,
            outDir = ctx.out,
            testParallelism = testParallelism,
            maxTestForks = maxTestForks,
            flushIntervalMs = flushInterval
          )
          JUnitXmlReportWriter
            .outputDir(ctx.module, forkedRun.runDir)
            .foreach(JUnitXmlReportWriter.writeReports(forkedRun.results, _))
          forkedRun.results
        }
      },
      isResultSuccessful = _.success
      // summarize = (results, notifs) => TestResultsSummary.summarize(results.map((m, r) => m.id -> r), notifs)
    )

